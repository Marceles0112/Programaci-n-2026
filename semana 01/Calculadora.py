#Entradas
num1 = int(input('Ingrese el primer número: '))
num2 = int(input('Ingrese el segundo número: '))
#Procesos
suma = num1 + num2
resta = num1 - num2
multiplicación = num1 * num2
división = num1 / num2
#Salidas
print('suma es:', suma)
print('resta es:', resta)
print('multiplicación es:', multiplicación)
print('división es:', división)
print(f"La multiplicación de {num1} * {num2} = {multiplicación}")

