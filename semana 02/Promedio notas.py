#Un estudiante necesita calcular su nota final basada en 3 exámenes. Diseña la lógica para promediar tres números.
#Entrada
nota1 = int(input('Ingrese nota1: '))
nota2 = int(input('Ingrese nota2: '))
nota3 = int(input('Ingrese nota3: '))

#Proceso
promedio = (nota1 + nota2 + nota3 ) / 3

#Salida
print('Tu promedio final es: ', promedio)
            